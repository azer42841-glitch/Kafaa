-- منصة سلاسة المعرفية: المخطط الأساسي (utf8mb4, InnoDB)
CREATE TABLE IF NOT EXISTS settings (k VARCHAR(64) PRIMARY KEY, v TEXT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login_at DATETIME NULL,
  country CHAR(2) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS courses (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(40) NOT NULL UNIQUE,
  title_en VARCHAR(120) NOT NULL, title_ar VARCHAR(120) NOT NULL,
  description_ar VARCHAR(500) NOT NULL DEFAULT '',
  icon VARCHAR(16) NOT NULL DEFAULT '📘',
  template VARCHAR(30) NOT NULL DEFAULT 'general',
  ord SMALLINT NOT NULL DEFAULT 0,
  published TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS levels (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  course_id INT UNSIGNED NOT NULL, ord SMALLINT NOT NULL,
  title_en VARCHAR(120) NOT NULL, title_ar VARCHAR(120) NOT NULL,
  description_ar VARCHAR(500) NOT NULL DEFAULT '',
  UNIQUE KEY uq_level (course_id, ord),
  FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS units (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  level_id INT UNSIGNED NOT NULL, ord SMALLINT NOT NULL,
  title_en VARCHAR(120) NOT NULL, title_ar VARCHAR(120) NOT NULL,
  FOREIGN KEY (level_id) REFERENCES levels(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS lessons (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  unit_id INT UNSIGNED NOT NULL, ord SMALLINT NOT NULL,
  title_en VARCHAR(160) NOT NULL, title_ar VARCHAR(160) NOT NULL,
  published TINYINT(1) NOT NULL DEFAULT 0,
  standard VARCHAR(20) NOT NULL DEFAULT '',
  reviewed_at DATE NULL,
  FOREIGN KEY (unit_id) REFERENCES units(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS lesson_blocks (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  lesson_id INT UNSIGNED NOT NULL, ord SMALLINT NOT NULL,
  type VARCHAR(20) NOT NULL, title VARCHAR(160) NOT NULL DEFAULT '',
  body MEDIUMTEXT NOT NULL,
  FOREIGN KEY (lesson_id) REFERENCES lessons(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS progress (
  user_id INT UNSIGNED NOT NULL, lesson_id INT UNSIGNED NOT NULL,
  done_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, lesson_id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (lesson_id) REFERENCES lessons(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS level_access (
  user_id INT UNSIGNED NOT NULL, level_id INT UNSIGNED NOT NULL,
  granted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, level_id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (level_id) REFERENCES levels(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rate_events (id BIGINT AUTO_INCREMENT PRIMARY KEY, k VARCHAR(80) NOT NULL, at INT UNSIGNED NOT NULL, KEY (k, at)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_log (id BIGINT AUTO_INCREMENT PRIMARY KEY, at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, actor VARCHAR(80) NOT NULL, action VARCHAR(80) NOT NULL, detail VARCHAR(300) NOT NULL DEFAULT '') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ai_usage (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NULL,
  feature VARCHAR(30) NOT NULL,
  model VARCHAR(80) NOT NULL DEFAULT '',
  tok_in INT UNSIGNED NOT NULL DEFAULT 0,
  tok_out INT UNSIGNED NOT NULL DEFAULT 0,
  audio_sec INT UNSIGNED NOT NULL DEFAULT 0,
  cost_usd DECIMAL(10,6) NOT NULL DEFAULT 0,
  ok TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_ai_user (user_id, created_at),
  KEY idx_ai_time (created_at, feature)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS countries (
  code CHAR(2) PRIMARY KEY, name_ar VARCHAR(40) NOT NULL, name_en VARCHAR(40) NOT NULL,
  flag VARCHAR(8) NOT NULL DEFAULT '', ord SMALLINT NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1, featured TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS lesson_countries (
  lesson_id INT UNSIGNED NOT NULL, country CHAR(2) NOT NULL,
  PRIMARY KEY (lesson_id, country),
  FOREIGN KEY (lesson_id) REFERENCES lessons(id) ON DELETE CASCADE,
  FOREIGN KEY (country) REFERENCES countries(code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
